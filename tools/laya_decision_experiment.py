def row_document(case):
    questions = deepcopy(DECISION_QUESTIONS)
    if case["scope"] != "group":
        questions["action"]["criteria"].pop("interject", None)
    facts = {
        "message_kind": case["message_kind"],
        "user_text": case["text"],
        "scope_kind": case["scope"],
    }
    return {
        "state": build_state(facts),
        "questions": questions,
        "expected": case["expected"],
        "text": case["text"],
        "scope": case["scope"],
        "message_kind": case["message_kind"],
    }


def write_jsonl(path: Path, cases) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = [row_document(case) for case in cases]
    seen = set()
    for row in rows:
        state = row["state"]
        if state in seen:
            raise ValueError(f"duplicate case in {path}: {state}")
        seen.add(state)
        if set(row["expected"]) != set(row["questions"]):
            raise ValueError("every decision question must have exactly one expected label")
        for name, label in row["expected"].items():
            if label not in row["questions"][name]["criteria"]:
                raise ValueError(f"label {label!r} is not valid for {name}")
    payload = "".join(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n" for row in rows)
    path.write_text(payload, encoding="utf-8", newline="\n")


def generate(args) -> None:
    train, evaluate = datasets()
    supplemental = supplemental_training_cases()
    balanced = balanced_training_cases()
    correct_obvious_intent_labels(supplemental)
    correct_obvious_intent_labels(balanced)
    train.extend(supplemental)
    train.extend(balanced)
    challenge = challenge_dataset()
    correct_obvious_intent_labels(challenge)
    if {item["text"] for item in train} & {item["text"] for item in evaluate}:
        raise ValueError("training and evaluation utterances must be disjoint")
    if {item["text"] for item in train} & {item["text"] for item in challenge}:
        raise ValueError("training and challenge utterances must be disjoint")
    if {item["text"] for item in evaluate} & {item["text"] for item in challenge}:
        raise ValueError("regression and challenge utterances must be disjoint")
    output = Path(args.output_dir)
    write_jsonl(output / "train.jsonl", train)
    write_jsonl(output / "eval.jsonl", evaluate)
    write_jsonl(output / "challenge.jsonl", challenge)
    print(json.dumps({"original_train_cases": len(train) - len(supplemental) - len(balanced),
                      "supplemental_train_cases": len(supplemental) + len(balanced),
                      "targeted_supplement_cases": len(supplemental),
                      "balanced_expansion_cases": len(balanced),
                      "train_cases": len(train), "eval_cases": len(evaluate),
                      "challenge_cases": len(challenge),
                      "train_decisions": len(train) * len(DEFAULT_LABELS),
                      "eval_decisions": len(evaluate) * len(DEFAULT_LABELS),
                      "challenge_decisions": len(challenge) * len(DEFAULT_LABELS),
                      "output_dir": str(output.resolve())}, ensure_ascii=False))


def train(args) -> None:
    import torch
    import laya.train as laya_train
    from laya.train import TrainConfig, finetune

    if not torch.cuda.is_available():
        raise RuntimeError("the isolated training Python has no CUDA-enabled PyTorch")
    config = TrainConfig(
        epochs=args.epochs,
        micro_batch=args.micro_batch,
        grad_accum=args.grad_accum,
        encoder_lr=args.encoder_lr,
        head_lr=args.head_lr,
        min_lr=args.min_lr,
        loss="soft-ce",
        shuffle_options=("choice",),
        seed=args.seed,
        max_len=512,
        head_max_len=256,
        amp=True,
        gradient_checkpointing=True,
        calib_max=400,
        calib_frac=0.1,
        eval_data=args.eval_data,
        log_every=10,
    )

    # Laya 0.4.0 evaluates before train_model moves its CPU-loaded checkpoint to the device.
    load_checkpoint = laya_train.load_checkpoint

    def load_checkpoint_on_cuda(model_dir):
        model, tokenizer, model_config = load_checkpoint(model_dir)
        return model.to("cuda"), tokenizer, model_config

    calibration_records = laya_train.calibration_records

    def calibration_records_single_item(*positional, **keywords):
        keywords["batch_size"] = 1
        return calibration_records(*positional, **keywords)

    laya_train.load_checkpoint = load_checkpoint_on_cuda
    laya_train.calibration_records = calibration_records_single_item
    report = finetune(args.train_data, args.base, args.output_dir, config=config, device="cuda")
    print(json.dumps(report, ensure_ascii=False, default=str, sort_keys=True))


def _score_rows(agent, rows):
    correct = {}
    totals = {}
    confusion = {}
    latencies = []
    errors = []
    for index, row in enumerate(rows, 1):
        start = time.perf_counter()
        result = agent.predict(row["state"], row["questions"])
        latencies.append((time.perf_counter() - start) * 1000)
        answers = result["answers"]
        for field, expected in row["expected"].items():
            predicted = answers[field]["choice"]
            totals[field] = totals.get(field, 0) + 1
            correct[field] = correct.get(field, 0) + int(predicted == expected)
            field_confusion = confusion.setdefault(field, {})
            actual_row = field_confusion.setdefault(expected, {})
            actual_row[predicted] = actual_row.get(predicted, 0) + 1
            if predicted != expected:
                errors.append({"case": index, "text": row.get("text", ""),
                               "field": field, "expected": expected, "predicted": predicted})
    per_field = {name: {"correct": correct[name], "total": count,
                        "accuracy": round(correct[name] / count, 4)}
                 for name, count in totals.items()}
    return {
        "cases": len(rows),
        "decisions": sum(totals.values()),
        "accuracy": round(sum(correct.values()) / sum(totals.values()), 4),
        "per_field": per_field,
        "confusion": confusion,
        "errors": errors,
        "latency_ms": {
            "p50": round(statistics.median(latencies), 2),
            "p95": round(sorted(latencies)[max(0, int(len(latencies) * 0.95) - 1)], 2),
        },
    }


def _score(agent, cases):
    return _score_rows(agent, [row_document(case) for case in cases])


