def add_cases(target, texts, *, scope="private", message_kind="text", **labels):
    merged = {**DEFAULT_LABELS, **labels}
    for text in texts:
        target.append({"scope": scope, "message_kind": message_kind, "text": text, "expected": dict(merged)})


def correct_obvious_intent_labels(cases):
    summarize = re.compile(
        r"(?:总结|概括|归纳|提炼|摘要).{0,30}(?:这条|这些|这段|这份|下面|本次|这次|会议|报告|文章|对话|记录|材料|访谈|评论|观点|结论|进展|周报|邮件|日志|复盘|讨论|第一段|第二段|段落|正文|主要意思|主要主题|各自限制|內容|内容|文本|新闻|合同|反馈|问卷|结果|事件)"
        r"|(?:总结|概括|归纳|提炼|摘要).{0,12}(?:大家|双方|各自|主要观点|核心观点|共同点|不同点)"
        r"|整理成.{0,10}(?:列表|清单|摘要|要点|概述|结论|笔记|汇总)"
    )
    explain = re.compile(
        r"为什么|为何|有什么区别|区别是什么|逐步(?:解释|说明|讲解)|讲清楚.{0,24}(?:原因|原理|区别|含义|关系|过程|影响)"
        r"|(?:原因|原理|含义)是什么|说明.{0,24}(?:原因|原理|区别|含义|過程|过程|关系|影响)"
        r"|详细(?:解释|说明|讲解|讲|比较)|逐项解释|分析.{0,24}(?:原因|影响|风险|差异|后果|过程|趋势|依据|原理|优缺点|故障|问题)"
        r"|(?:原因|原理|背景|影响|风险|差异).{0,24}(?:讲清楚|展开说明|分析|解释)"
        r"|(?:如何|怎样|怎么)(?:做|制作|使用|处理|安装|准备|操作|更换|修理|配置|整理|计算|比较|选择|解决|运行|查询|泡|洗|煮|保存|写|判断|理解|区分|规划|恢复|备份|换胎|管理)"
        r"|怎么(?:才能|才可以)"
        r"|解释(?=(?:一下|下|什么|这|这次|这份|名词|HTTP|为什么|为何|如何|原因|原理|登录失败|引用原文|一道题))"
    )
    for case in cases:
        expected = case["expected"]
        if expected.get("reply_intent") != "answer":
            continue
        if summarize.search(case["text"]):
            expected["reply_intent"] = "summarize"
        elif explain.search(case["text"]):
            expected["reply_intent"] = "explain"


